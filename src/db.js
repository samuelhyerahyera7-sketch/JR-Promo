// Schema changes after the first PostgreSQL release. Each entry upgrades the database by one version.
const MIGRATIONS = [];

const value = (p) => (p === undefined ? null : typeof p === 'boolean' ? (p ? 1 : 0) : p);
const isNamed = (params) =>
  params.length === 1 && params[0] !== null && typeof params[0] === 'object' && !Array.isArray(params[0]) && !Buffer.isBuffer(params[0]);

/**
 * Placeholders: '?' (in order), '?1' (numbered) or ':name' with one object of values.
 * Booleans become 1/0 (flags are INTEGER columns) and undefined becomes NULL.
 */
function prepare(sql, params) {
  if (isNamed(params)) {
    const names = [];
    const text = sql.replace(/(?<![:\w]):([a-z_]+)/g, (m, name) => {
      if (!(name in params[0])) throw new Error(`Missing SQL parameter :${name}`);
      if (!names.includes(name)) names.push(name);
      return `$${names.indexOf(name) + 1}`;
    });
    return { text, values: names.map((n) => value(params[0][n])) };
  }
  if (/\?\d/.test(sql)) {
    const text = sql.replace(/\?(\d+)/g, '$$$1');
    if (text.includes('?')) throw new Error(`Don't mix ?1 and ? placeholders: ${sql.slice(0, 120)}`);
    return { text, values: params.map(value) };
  }
  let n = 0;
  const text = sql.replace(/\?/g, () => `$${++n}`);
  if (n !== params.length) throw new Error(`SQL expects ${n} parameter(s), got ${params.length}: ${sql.slice(0, 120)}`);
  return { text, values: params.map(value) };
}

/**
 * The database handle the app passes around. Every call is async:
 *   await db.get(sql, ...params)    first row or undefined
 *   await db.all(sql, ...params)    all rows
 *   await db.run(sql, ...params)    { changes }
 *   await db.insert(sql, ...params) id of the new row
 * Inside db.tx() the same calls run on the transaction's connection automatically.
 */
function createDb(pool) {
  const als = new AsyncLocalStorage();
  const client = () => als.getStore() || pool;
  const query = async (sql, params) => {
    const q = prepare(sql, params);
    return client().query(q.text, q.values);
  };
  return {
    pool,
    get: async (sql, ...params) => (await query(sql, params)).rows[0],
    all: async (sql, ...params) => (await query(sql, params)).rows,
    run: async (sql, ...params) => ({ changes: (await query(sql, params)).rowCount }),
    insert: async (sql, ...params) => (await query(`${sql} RETURNING id`, params)).rows[0].id,
    exec: (sql) => client().query(sql),
    /** A statement to run many times: stmt.get/all/run(...params), all async. */
    stmt(sql) {
      return {
        get: async (...params) => (await query(sql, params)).rows[0],
        all: async (...params) => (await query(sql, params)).rows,
        run: async (...params) => ({ changes: (await query(sql, params)).rowCount }),
        insert: async (...params) => (await query(`${sql} RETURNING id`, params)).rows[0].id,
      };
    },
    /** Run fn in one transaction; it rolls back if fn throws. Nested calls join the outer transaction. */
    async tx(fn) {
      if (als.getStore()) return fn();
      const conn = await pool.connect();
      try {
        await conn.query('BEGIN');
        const result = await als.run(conn, fn);
        await conn.query('COMMIT');
        return result;
      } catch (err) {
        await conn.query('ROLLBACK').catch(() => {});
        throw err;
      } finally {
        conn.release();
      }
    },
    close: () => pool.end(),
  };
}

async function migrate(db) {
  await db.tx(async () => {
    // Only one instance migrates at a time
    await db.exec('SELECT pg_advisory_xact_lock(4711)');
    await db.exec('CREATE TABLE IF NOT EXISTS schema_version (version INTEGER NOT NULL)');
    let row = await db.get('SELECT version FROM schema_version');
    if (!row) {
      await db.exec(SCHEMA);
      await db.run('INSERT INTO schema_version (version) VALUES (1)');
      row = { version: 1 };
    }
    for (let v = row.version; v <= MIGRATIONS.length; v++) {
      await db.exec(MIGRATIONS[v - 1]);
      await db.run('UPDATE schema_version SET version = ?', v + 1);
    }
  });
}

/**
 * Connect to PostgreSQL (DATABASE_URL, e.g. Supabase's transaction pooler) and bring
 * the schema up to date. Pass { reset: true } to wipe the schema first (tests only).
 */
async function open(url = process.env.DATABASE_URL, { reset = false, max = 5 } = {}) {
  if (!url) throw new Error('DATABASE_URL is not set');
  const local = /@(localhost|127\.0\.0\.1)[:/]/.test(url);
  const pool = new pg.Pool({
    connectionString: url,
    max,
    ssl: local ? false : { rejectUnauthorized: false },
    idleTimeoutMillis: 10000,
  });
  const db = createDb(pool);
  if (reset) await db.exec('DROP SCHEMA public CASCADE; CREATE SCHEMA public;');
  await migrate(db);
  return db;
}

/** Run fn inside a transaction; rolls back on any thrown error. */
const tx = (db, fn) => db.tx(fn);

module.exports = { open, tx, SCHEMA, SCHEMA_VERSION: MIGRATIONS.length + 1 };
